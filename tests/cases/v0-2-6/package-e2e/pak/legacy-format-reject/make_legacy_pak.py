#!/usr/bin/env python3
# =============================================================================
# make_legacy_pak.py - materializes app/legacy-format-v1.cp3pak (deterministic).
#
# The .cp3pak is a binary member (gzip + USTAR tar), and the agents that
# authored this fixture never ran code, so the binary file is NOT checked in
# (.gitignore also ignores *.cp3pak, so it could not be committed anyway).
# Run this once after cloning, before the verification invocation:
#
#   python tests/cases/v0-2-6/package-e2e/pak/legacy-format-reject/make_legacy_pak.py
#
# Output is byte-identical on every run (tar member headers and the gzip
# stream are pinned to mtime 0), mirroring tests/cli/run_cli_tests.py
# (write_cp3pak / build_source_cp3pak: USTAR tar inside gzip, mtime zero).
#
# The pak is a hand-fabricated LEGACY (formatVersion 1) archive:
#   cp3pak.json        container manifest, formatVersion 1 (NOT the current 2)
#   package.json       the author's manifest, verbatim
#   pak/src/tide.cpp   transpiled C++ (self-contained translation unit)
#   pak/src/tide.hpp   generated header
# It carries NO .cp3 sources (not even index.cp3) - the property a modern
# install must reject cleanly after the v0.2.6 format bump.
# =============================================================================
import gzip
import io
import json
import sys
import tarfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
DEST = HERE / "app" / "legacy-format-v1.cp3pak"

TIDE_CPP = (
    "// Generated by cp3c codegen from `src/tide` - do not edit.\n"
    "namespace cp3_mod_src_tide {\n"
    "double surge(double a, double b) { return a + b; }\n"
    "}  // namespace cp3_mod_src_tide\n"
)

TIDE_HPP = (
    "// Generated by cp3c codegen from `src/tide` - do not edit.\n"
    "#ifndef CP3_GENERATED_SRC_TIDE_HPP\n"
    "#define CP3_GENERATED_SRC_TIDE_HPP\n"
    "namespace cp3_mod_src_tide {\n"
    "double surge(double a, double b);\n"
    "}  // namespace cp3_mod_src_tide\n"
    "#endif\n"
)


def write_cp3pak(destination: Path, members: list[tuple[str, bytes]]) -> None:
    """Write a deterministic .cp3pak (USTAR tar inside gzip, mtime zero)."""
    tar_buffer = io.BytesIO()
    with tarfile.open(fileobj=tar_buffer, mode="w",
                      format=tarfile.USTAR_FORMAT) as archive:
        for member_name, data in members:
            info = tarfile.TarInfo(member_name)
            info.size = len(data)
            info.mtime = 0
            info.mode = 0o644
            info.uid = 0
            info.gid = 0
            archive.addfile(info, io.BytesIO(data))
    destination.parent.mkdir(parents=True, exist_ok=True)
    with destination.open("wb") as raw:
        with gzip.GzipFile(fileobj=raw, mode="wb", mtime=0) as compressed:
            compressed.write(tar_buffer.getvalue())


def main() -> int:
    manifest = {
        "formatVersion": 1,
        "name": "legacy_tide",
        "version": "1.2.3",
        "main": "index.cp3",
    }
    package_json = {
        "name": "legacy_tide",
        "version": "1.2.3",
        "description": "hand-fabricated legacy-format fixture",
        "type": "package",
        "main": "src/tide.cp3",
    }
    members = [
        ("cp3pak.json",
         (json.dumps(manifest, indent=2) + "\n").encode("utf-8")),
        ("package.json",
         (json.dumps(package_json, indent=2) + "\n").encode("utf-8")),
        ("pak/src/tide.cpp", TIDE_CPP.encode("utf-8")),
        ("pak/src/tide.hpp", TIDE_HPP.encode("utf-8")),
    ]
    write_cp3pak(DEST, members)
    print(f"wrote {DEST} ({DEST.stat().st_size} bytes, 4 members)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
