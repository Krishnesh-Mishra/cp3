"""word-frequency (python entry) -- count 3,000,000 picks from a 64-word
vocabulary generated by a pinned integer LCG, then fold the counts into one
deterministic checksum.

Run:   python main.py

Same workload and same output in every language entry. This is the
hash-map-shaped task: every pick is a string-keyed lookup + increment, and the
final fold walks the vocabulary in a fixed order so no language's map
iteration order can leak into the output. CPython's dict is one of the fastest
implementations of this kind of counting, so this is where Python does not
look like the compute-single picture.
"""

CORPUS = 3_000_000
VOCAB = 64


def main():
    words = [f"word{i:02d}" for i in range(VOCAB)]

    counts = {}

    state = 1
    for _ in range(CORPUS):
        state = (state * 48271) % 2147483647
        word = words[state % VOCAB]
        counts[word] = counts.get(word, 0) + 1

    checksum = 0
    for word in words:
        checksum = (checksum * 31 + counts.get(word, 0)) % 1000000007
    print(checksum)


if __name__ == "__main__":
    main()
