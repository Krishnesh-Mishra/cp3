#!/usr/bin/env python3
# =============================================================================
# tools/check_cp3002.py - the zero-placeholder gate.
#
# CP3002 ("not implemented in this build yet") is retiring. This gate makes the
# retirement enforceable: it scans src/, tests/, docs/ and packaging/ for the
# diagnostic token and for the source markers that keep it alive.
#
# Usage:
#
#     python tools/check_cp3002.py                 # scan; file:line per hit; exit 1
#     python tools/check_cp3002.py --report        # same, grouped by marker
#     python tools/check_cp3002.py --baseline FILE # exit 1 only on new hits
#     python tools/check_cp3002.py --write-baseline FILE
#
# The default mode is the gate: every hit is printed as `path:line: marker:
# text`, and the process exits 1 while any remain. `--report` adds marker
# headings without changing the exit status. `--baseline` is a temporary
# comparison mode for a wave that is still removing existing hits: it allows
# the recorded counts and fails only when a file/marker count grows. The
# baseline must be empty (comments only) in the final landing; an empty
# baseline makes --baseline behave exactly like the default gate.
#
# Only two things are skipped: this scanner file and generated build output
# directories (build, out, dist, caches, node_modules). Everything else in the
# four roots is scanned as raw bytes, so no source file can hide a marker.
#
# Standard library only. No build, compiler or third-party tool is required.
# =============================================================================

from __future__ import annotations

import argparse
import os
import re
import sys
from collections import Counter
from dataclasses import dataclass

# Longest marker first so `kNotImplemented` is not counted as `NotImplemented`.
MARKERS = (
    "CP3002",
    "kNotImplemented",
    "not_implemented",
    "notImplemented",
    "NotImplemented",
)
RE_MARKER = re.compile("|".join(re.escape(marker) for marker in MARKERS))
RE_MARKER_BYTES = re.compile(RE_MARKER.pattern.encode("ascii"))

SCAN_ROOTS = ("src", "tests", "docs", "packaging")
TEXT_LIMIT = 240

# Generated build output and tool caches. A source tree may nest a build
# directory under a scanned root, so the names are pruned at every level.
SKIP_DIR_NAMES = frozenset({
    "build",
    "out",
    "dist",
    "node_modules",
    "__pycache__",
    ".cache",
    ".git",
    ".hg",
    ".svn",
    ".mypy_cache",
    ".pytest_cache",
    ".ruff_cache",
    ".venv",
    "venv",
})

SCANNER_PATH = os.path.normcase(os.path.abspath(__file__))
DEFAULT_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

BASELINE_HEADER = (
    "# CP3002 interim baseline (TEMPORARY).\n"
    "# Generated by tools/check_cp3002.py --write-baseline.\n"
    "# Format: <count>\\t<path>\\t<marker>\n"
    "# This file must be EMPTY (comments only) in the final landing.\n"
    "# Regenerate only while the feature lanes are still removing markers.\n"
)


@dataclass(frozen=True)
class Hit:
    path: str
    line: int
    marker: str
    text: str


def rel_path(root, path):
    return os.path.relpath(path, root).replace("\\", "/")


def clip(text, limit=TEXT_LIMIT):
    if len(text) <= limit:
        return text
    return text[:limit].rstrip() + " ..."


def iter_files(root):
    """Yield every scannable file under the four roots."""
    found = False
    for area in SCAN_ROOTS:
        area_root = os.path.join(root, area)
        if not os.path.isdir(area_root):
            continue
        found = True
        for dirpath, dirnames, filenames in os.walk(area_root):
            dirnames[:] = sorted(
                name for name in dirnames if name.lower() not in SKIP_DIR_NAMES
            )
            for name in sorted(filenames):
                path = os.path.join(dirpath, name)
                if os.path.normcase(os.path.abspath(path)) == SCANNER_PATH:
                    continue
                yield path
    if not found:
        raise FileNotFoundError(
            "none of the scan roots exist under "
            f"{root}: {', '.join(SCAN_ROOTS)}"
        )


def scan_file(root, path):
    """Return the marker hits in one file, reading it as bytes."""
    try:
        with open(path, "rb") as handle:
            data = handle.read()
    except OSError:
        return []
    if not RE_MARKER_BYTES.search(data):
        return []
    rel = rel_path(root, path)
    hits = []
    for lineno, raw in enumerate(data.splitlines(), start=1):
        if not RE_MARKER_BYTES.search(raw):
            continue
        text = clip(raw.decode("utf-8", "replace").strip())
        for match in RE_MARKER_BYTES.finditer(raw):
            hits.append(Hit(rel, lineno, match.group().decode("ascii"), text))
    return hits


def scan(root):
    hits = []
    for path in iter_files(root):
        hits.extend(scan_file(root, path))
    hits.sort(key=lambda hit: (hit.path, hit.line, MARKERS.index(hit.marker)))
    return hits


def count_by(hits, key):
    return Counter(key(hit) for hit in hits)


def area_of(hit):
    return hit.path.split("/", 1)[0] if "/" in hit.path else hit.path


def print_summary(hits, root):
    print("zero-placeholder gate - retired diagnostic and source markers")
    print(f"root: {root}")
    print("scan roots: " + ", ".join(SCAN_ROOTS))
    print()
    print(f"total: {len(hits)} hit(s) in {len({hit.path for hit in hits})} file(s)")
    by_marker = count_by(hits, lambda hit: hit.marker)
    for marker in MARKERS:
        print(f"  {marker:<18} {by_marker.get(marker, 0)}")
    by_area = count_by(hits, area_of)
    print("by area:")
    for area in SCAN_ROOTS:
        print(f"  {area:<18} {by_area.get(area, 0)}")


def print_hits(hits):
    print()
    print("hits:")
    for hit in hits:
        print(f"  {hit.path}:{hit.line}: {hit.marker}: {hit.text}")


def print_report(hits):
    print()
    print("hits by marker:")
    for marker in MARKERS:
        marker_hits = [hit for hit in hits if hit.marker == marker]
        if not marker_hits:
            continue
        print(f"  {marker} ({len(marker_hits)})")
        for hit in marker_hits:
            print(f"    {hit.path}:{hit.line}: {hit.text}")


def load_baseline(path):
    counts = Counter()
    with open(path, "r", encoding="utf-8", errors="replace") as handle:
        for lineno, line in enumerate(handle, start=1):
            line = line.rstrip("\n")
            if not line.strip() or line.lstrip().startswith("#"):
                continue
            parts = line.split("\t")
            if len(parts) != 3:
                raise ValueError(
                    f"{path}:{lineno}: expected <count>\\t<path>\\t<marker>"
                )
            count_text, rel, marker = parts
            try:
                count = int(count_text)
            except ValueError as exc:
                raise ValueError(
                    f"{path}:{lineno}: count is not an integer: {count_text!r}"
                ) from exc
            if count < 0:
                raise ValueError(f"{path}:{lineno}: count must not be negative")
            if marker not in MARKERS:
                raise ValueError(
                    f"{path}:{lineno}: unknown marker {marker!r}; "
                    f"known markers: {', '.join(MARKERS)}"
                )
            counts[(rel.replace("\\", "/"), marker)] += count
    return counts


def write_baseline(path, hits):
    counts = count_by(hits, lambda hit: (hit.path, hit.marker))
    with open(path, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(BASELINE_HEADER)
        for (rel, marker), count in sorted(
            counts.items(), key=lambda item: (item[0][0], MARKERS.index(item[0][1]))
        ):
            handle.write(f"{count}\t{rel}\t{marker}\n")


def compare_baseline(hits, baseline):
    current = count_by(hits, lambda hit: (hit.path, hit.marker))
    extra = {}
    for key, count in current.items():
        known = baseline.get(key, 0)
        if count > known:
            extra[key] = count - known
    filtered = []
    remaining = dict(extra)
    for hit in hits:
        key = (hit.path, hit.marker)
        if remaining.get(key, 0) > 0:
            filtered.append(hit)
            remaining[key] -= 1
    stale = sum(max(0, count - current.get(key, 0)) for key, count in baseline.items())
    return filtered, stale


def main(argv=None):
    parser = argparse.ArgumentParser(
        description=(
            "Fail on CP3002 / notImplemented markers in src, tests, docs and "
            "packaging."
        )
    )
    parser.add_argument(
        "--report",
        action="store_true",
        help="group the file:line hits by marker",
    )
    parser.add_argument(
        "--strict",
        action="store_true",
        help="kept for compatibility; the gate is strict by default",
    )
    parser.add_argument(
        "--baseline",
        metavar="FILE",
        help="temporary comparison: exit 1 only on hits above the recorded counts",
    )
    parser.add_argument(
        "--write-baseline",
        metavar="FILE",
        help="write the current hits to FILE as an interim baseline",
    )
    parser.add_argument(
        "--root",
        default=None,
        help="repository root (default: the parent of tools/)",
    )
    args = parser.parse_args(argv)

    if args.strict and args.baseline:
        parser.error("--strict and --baseline are mutually exclusive")
    if args.strict and args.write_baseline:
        parser.error("--strict and --write-baseline are mutually exclusive")
    if args.baseline and args.write_baseline:
        parser.error("--baseline and --write-baseline are mutually exclusive")

    root = os.path.abspath(args.root) if args.root else DEFAULT_ROOT
    try:
        hits = scan(root)
    except FileNotFoundError as exc:
        sys.stderr.write(f"check_cp3002: {exc}\n")
        return 2

    if args.write_baseline:
        write_baseline(args.write_baseline, hits)
        print(f"wrote interim baseline: {args.write_baseline}")
        print(f"recorded: {len(hits)} hit(s) in {len({hit.path for hit in hits})} file(s)")
        return 0

    if args.baseline:
        try:
            baseline = load_baseline(args.baseline)
        except OSError as exc:
            sys.stderr.write(f"check_cp3002: cannot read baseline: {exc}\n")
            return 2
        except ValueError as exc:
            sys.stderr.write(f"check_cp3002: invalid baseline: {exc}\n")
            return 2

        new_hits, stale = compare_baseline(hits, baseline)
        recorded = sum(baseline.values())
        print_summary(hits, root)
        print()
        print(f"baseline: {args.baseline} ({recorded} recorded hit(s))")
        print(
            f"new: {len(new_hits)} hit(s) in "
            f"{len({hit.path for hit in new_hits})} file(s)"
        )
        if new_hits:
            print_hits(new_hits)
        if stale:
            print(f"stale: {stale} baseline hit(s) no longer present (allowed)")
        if new_hits:
            print()
            print("zero-placeholder gate FAILED: new marker hits above the interim baseline.")
            return 1
        print()
        print("zero-placeholder gate OK: no new marker hits above the interim baseline.")
        return 0

    print_summary(hits, root)
    if args.report:
        print_report(hits)
    else:
        print_hits(hits)

    if hits:
        print()
        print(f"zero-placeholder gate FAILED: {len(hits)} marker hit(s) remain.")
        return 1
    print()
    print("zero-placeholder gate OK: no marker hits.")
    return 0


if __name__ == "__main__":
    for stream in (sys.stdout, sys.stderr):
        if hasattr(stream, "reconfigure"):
            stream.reconfigure(encoding="utf-8", errors="replace")
    sys.exit(main())
