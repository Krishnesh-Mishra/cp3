#!/usr/bin/env python3
import hashlib
import textwrap

INPUT = "third_party/openssl/cacert.pem"
OUTPUT = "src/std/network/tls/cacert.hpp"

with open(INPUT, "rb") as fh:
    data = fh.read()

with open(OUTPUT, "w", encoding="ascii") as out:
    out.write("// =============================================================================\n")
    out.write("// src/std/network/tls/cacert.hpp - embedded Mozilla CA bundle.\n")
    out.write("//\n")
    out.write("// Generated by tools/embed-cacert.py from third_party/openssl/cacert.pem\n")
    out.write("// (SHA-256 " + hashlib.sha256(data).hexdigest() + "); do not edit by hand.\n")
    out.write("// The bytes ship inside every TLS-linked binary so a generated program trusts\n")
    out.write("// public CAs without a system store or vendored cacert.pem on disk.\n")
    out.write("// =============================================================================\n")
    out.write("#pragma once\n\n#include <cstddef>\n#include <cstdint>\n\n")
    out.write("namespace cp3 {\nnamespace runtime::network::tls::detail {\n\n")
    out.write("inline constexpr std::uint8_t kCacertPem[] = {\n")
    for i in range(0, len(data), 24):
        row = ", ".join(str(b) for b in data[i:i + 24])
        out.write("    " + row + ",\n")
    out.write("};\n\n")
    out.write("inline constexpr std::size_t kCacertPemLen = sizeof(kCacertPem);\n\n")
    out.write("inline constexpr const std::uint8_t* cacert_hpp_bytes() noexcept {\n")
    out.write("    return kCacertPem;\n}\n\n")
    out.write("inline constexpr std::size_t cacert_hpp_length() noexcept {\n")
    out.write("    return kCacertPemLen;\n}\n\n")
    out.write("}  // namespace runtime::network::tls::detail\n}  // namespace cp3\n")
print("wrote", OUTPUT)
