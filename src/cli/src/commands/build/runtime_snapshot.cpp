// =============================================================================
// src/cli/src/commands/build/runtime_snapshot.cpp - runtime source snapshot
// (DEFINITIONS).
//
// OWNERSHIP: cli module (src/cli/**). Implements
// detail/core/runtime_snapshot.hpp.
//
// The snapshot mirrors the runtime's `cp3/` include tree under
// `<project>/.cp3/build/core/cp3-runtime/`:
//
//   core/runtime.hpp      <- src/runtime/include/cp3/core/runtime.hpp
//   core/runtime.cpp      <- src/runtime/src/core/runtime.cpp
//   async/eventloop.cpp   <- src/runtime/src/async/eventloop.cpp
//   typed_array.hpp       <- src/std/typed-arrays/include/cp3/typed_array.hpp
//
// It contains only the headers and the core runtime TUs, never the native
// std/third_party backends. The normal build continues to compile the shipped
// files; this tree exists so a user can read the exact runtime a generated
// program calls.
// =============================================================================
#include "detail/core/runtime_snapshot.hpp"

#include <cstdio>
#include <string>
#include <system_error>

#include "detail/core/util.hpp"

namespace cp3::cli {

namespace {

bool copyOne(const fs::path& from, const fs::path& to, bool verbose) {
    std::error_code ec;
    fs::create_directories(to.parent_path(), ec);
    if (ec) {
        std::fprintf(stderr, "cp3c: cannot create '%s' for the runtime snapshot\n",
                     to.parent_path().string().c_str());
        return false;
    }
    fs::copy_file(from, to, fs::copy_options::overwrite_existing, ec);
    if (ec) {
        std::fprintf(stderr, "cp3c: cannot copy '%s' to '%s'\n",
                     from.string().c_str(), to.string().c_str());
        return false;
    }
    if (verbose) {
        std::fprintf(stderr, "cp3c: runtime snapshot: %s\n",
                     to.string().c_str());
    }
    return true;
}

// Copies every regular file under `from` into `to`, preserving relative paths.
bool copyTree(const fs::path& from, const fs::path& to, bool verbose) {
    std::error_code ec;
    if (!fs::is_directory(from, ec)) return true;  // no tree, nothing to copy
    fs::recursive_directory_iterator it(from, ec);
    const fs::recursive_directory_iterator end;
    if (ec) return false;
    for (; it != end; it.increment(ec)) {
        if (ec) return false;
        if (!it->is_regular_file(ec)) continue;
        const fs::path rel = fs::relative(it->path(), from, ec);
        if (ec || rel.empty()) return false;
        if (!copyOne(it->path(), to / rel, verbose)) return false;
    }
    return true;
}

// True when `path` is inside `root` (the snapshot must not copy a path outside
// the runtime source tree).
bool isInside(const fs::path& path, const fs::path& root) {
    std::error_code ec;
    const fs::path rel = fs::relative(path, root, ec);
    if (ec || rel.empty()) return false;
    const std::string first = rel.begin()->string();
    return first != "..";
}

std::string readmeText() {
    return
        "Runtime snapshot generated by `cp3c build/run --show-runtime`.\n"
        "\n"
        "This directory mirrors the runtime headers and the core runtime\n"
        "translation units selected for this program. The `cp3/` include\n"
        "prefix is removed so the tree reads as:\n"
        "\n"
        "  core/runtime.hpp      src/runtime/include/cp3/core/runtime.hpp\n"
        "  core/runtime.cpp      src/runtime/src/core/runtime.cpp\n"
        "  async/eventloop.cpp   src/runtime/src/async/eventloop.cpp\n"
        "  typed_array.hpp       src/std/typed-arrays/include/cp3/typed_array.hpp\n"
        "\n"
        "The normal build does not compile these copies. They exist so the\n"
        "generated C++ and the runtime it calls can be inspected and optimized\n"
        "side by side. Regenerate them with `cp3c build --show-runtime` or\n"
        "`cp3c run --show-runtime`; `cp3c clean` removes them.\n";
}

}  // namespace

fs::path copyRuntimeSnapshot(const BuildLayout& layout, bool verbose) {
    const fs::path repo = repositoryRoot();
    if (repo.empty()) {
        std::fputs("cp3c: cannot locate the cp3 source tree for the runtime "
                   "snapshot\n", stderr);
        return {};
    }

    const fs::path root = layout.buildDir / "core" / "cp3-runtime";
    std::error_code ec;
    fs::remove_all(root, ec);
    if (ec) {
        std::fprintf(stderr, "cp3c: cannot clear the runtime snapshot at '%s'\n",
                     root.string().c_str());
        return {};
    }
    fs::create_directories(root, ec);
    if (ec) {
        std::fprintf(stderr, "cp3c: cannot create the runtime snapshot at '%s'\n",
                     root.string().c_str());
        return {};
    }

    // Every runtime header (core/, async/, parallel/).
    const fs::path includeRoot = resolveIncludeRoot(repo, "src/runtime/include");
    if (!copyTree(includeRoot / "cp3", root, verbose)) {
        std::fputs("cp3c: cannot copy the runtime headers into the snapshot\n",
                   stderr);
        return {};
    }

    // The always-available typed-array ABI header is part of every generated
    // program header even though it lives under src/std.
    const fs::path typedArray =
        resolveIncludeRoot(repo, "src/std/typed-arrays/include") /
        "cp3" / "typed_array.hpp";
    if (fs::is_regular_file(typedArray, ec) &&
        !copyOne(typedArray, root / "typed_array.hpp", verbose)) {
        return {};
    }

    // Only the core runtime TUs selected for this build. Native std backends
    // stay in their shipped trees; copying them would duplicate third_party.
    // The nested layout is the checkout/install layout; the flat fallback keeps
    // the snapshot working for an older packaged runtime tree.
    fs::path sourceRoot = repo / "src" / "runtime" / "src";
    if (!fs::is_directory(sourceRoot, ec)) {
        sourceRoot = repo / "src" / "runtime";
    }
    for (const fs::path& source : layout.runtimeSources) {
        if (!isInside(source, sourceRoot)) continue;
        const fs::path rel = fs::relative(source, sourceRoot, ec);
        if (ec || rel.empty()) continue;
        if (!copyOne(source, root / rel, verbose)) return {};
    }

    if (!writeTextFile(root / "README.txt", readmeText(), nullptr)) {
        std::fputs("cp3c: cannot write the runtime snapshot README\n", stderr);
        return {};
    }
    return root;
}

}  // namespace cp3::cli
