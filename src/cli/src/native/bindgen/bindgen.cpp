std::string Binder::cursorSpelling(CXCursor cursor) const {
    CXString text = lib_.clang_getCursorSpelling(cursor);
    const char* c = lib_.clang_getCString(text);
    std::string out = c == nullptr ? std::string() : std::string(c);
    lib_.clang_disposeString(text);
    return out;
}

std::string Binder::cursorUSR(CXCursor cursor) const {
    CXString text = lib_.clang_getCursorUSR(cursor);
    const char* c = lib_.clang_getCString(text);
    std::string out = c == nullptr ? std::string() : std::string(c);
    lib_.clang_disposeString(text);
    return out;
}


std::string Binder::cursorFile(CXCursor cursor) const {
    CXFile file = nullptr;
    unsigned line = 0;
    unsigned column = 0;
    unsigned offset = 0;
    lib_.clang_getExpansionLocation(lib_.clang_getCursorLocation(cursor), &file,
                                    &line, &column, &offset);
    (void)line;
    (void)column;
    (void)offset;
    if (file == nullptr) return {};
    CXString name = lib_.clang_getFileName(file);
    const char* c = lib_.clang_getCString(name);
    std::string out = c == nullptr ? std::string() : std::string(c);
    lib_.clang_disposeString(name);
    return out;
}

std::string Binder::qualifiedName(CXCursor cursor) const {
    std::vector<std::string> parts;
    CXCursor current = cursor;
    for (int depth = 0; depth < 32; ++depth) {
        const CXCursor parent = lib_.clang_getCursorSemanticParent(current);
        if (lib_.clang_Cursor_isNull(parent)) break;
        const CXCursorKind kind = lib_.clang_getCursorKind(parent);
        if (kind != CXCursor_Namespace && kind != CXCursor_ClassDecl &&
            kind != CXCursor_StructDecl && kind != CXCursor_UnionDecl) {
            break;
        }
        const std::string name = cursorSpelling(parent);
        if (!name.empty()) parts.push_back(name);
        current = parent;
    }
    std::string out;
    for (auto it = parts.rbegin(); it != parts.rend(); ++it) {
        out += *it + "::";
    }
    out += cursorSpelling(cursor);
    return out;
}


bool Binder::inBoundHeader(CXCursor cursor) const {
    if (lib_.clang_Location_isInSystemHeader(lib_.clang_getCursorLocation(cursor))) {
        return false;
    }
    const std::string file = cursorFile(cursor);
    if (file.empty()) return false;
    auto normalize = [](std::string path) {
        std::replace(path.begin(), path.end(), '\\', '/');
#if defined(_WIN32)
        std::transform(path.begin(), path.end(), path.begin(),
                       [](unsigned char c) { return static_cast<char>(std::tolower(c)); });
#endif
        return path;
    };
    const std::string normalized = normalize(file);
    if (request_.publicRoots.empty()) return true;
    for (const std::string& root : request_.publicRoots) {
        const std::string r = normalize(root);
        if (normalized == r ||
            (normalized.size() > r.size() && normalized.compare(0, r.size(), r) == 0 &&
             normalized[r.size()] == '/')) {
            return true;
        }
    }
    return false;
}

std::string Binder::uniqueName(const std::string& preferred,
                               const std::string& kind) {
    (void)kind;
    if (preferred.empty()) return preferred;
    if (usedNames_.insert(preferred).second) return preferred;
    for (int n = 2; n < 10000; ++n) {
        const std::string candidate = preferred + "_" + std::to_string(n);
        if (usedNames_.insert(candidate).second) return candidate;
    }
    return preferred;
}

void Binder::reject(const std::string& text) {
    if (text.empty()) return;
    for (const std::string& existing : module_.rejected) {
        if (existing == text) return;
    }
    module_.rejected.push_back(text);
}

void Binder::rejectCursor(CXCursor cursor, const std::string& kind,
                          const std::string& reason) {
    if (!inBoundHeader(cursor)) return;
    reject(kind + ": " + reason);
}

BindResult bindHeaders(const LibClang& lib, const BindRequest& request) {
    BindResult result;
    result.module.id = request.moduleId;
    result.module.source = request.source;
    result.module.includeDirs = request.includeDirs;
    result.module.defines = request.defines;
    result.module.libclangVersion = lib.version;

    Binder binder(lib, request, result.module);
    if (!binder.run(result.error)) return result;
    result.ok = true;
    return result;
}

