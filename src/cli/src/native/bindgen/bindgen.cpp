Binder::Binder(const LibClang& lib, const BindRequest& request,
               NativeModule& module)
    : lib_(lib), request_(request), module_(module) {}

bool Binder::run(std::string& error) {
    CXIndex index = lib_.clang_createIndex(0, 0);
    if (index == nullptr) {
        error = "libclang could not create an index";
        return false;
    }
    const std::string sourceName = request_.moduleId + "-native-install.cpp";
    std::string source = syntheticSource(request_);
    CXUnsavedFile unsaved{sourceName.c_str(), source.c_str(),
                          static_cast<unsigned long>(source.size())};

    std::vector<std::string> args{"-x", "c++", "-std=c++20",
                                  "-fparse-all-comments"};
    for (const std::string& arg : request_.clangArgs) {
        args.push_back(arg);
    }
    for (const std::string& dir : request_.includeDirs) {
        args.push_back("-I" + dir);
    }
    for (const std::string& define : request_.defines) {
        args.push_back("-D" + define);
    }
    std::vector<const char*> argv = cstrings(args);

    CXTranslationUnit tu = nullptr;
    const CXErrorCode rc = lib_.clang_parseTranslationUnit2(
        index, sourceName.c_str(), argv.data(), static_cast<int>(argv.size()),
        &unsaved, 1, CXTranslationUnit_KeepGoing, &tu);
    if (rc != CXError_Success || tu == nullptr) {
        error = "libclang could not parse the headers (error " +
                std::to_string(static_cast<int>(rc)) + ")";
        lib_.clang_disposeIndex(index);
        return false;
    }
    if (hasErrorDiagnostic(lib_, tu, error)) {
        error = "C++ header parse failed:\n" + error;
        lib_.clang_disposeTranslationUnit(tu);
        lib_.clang_disposeIndex(index);
        return false;
    }

    CXTargetInfo target = lib_.clang_getTranslationUnitTargetInfo(tu);
    if (target != nullptr) {
        CXString triple = lib_.clang_TargetInfo_getTriple(target);
        const char* text = lib_.clang_getCString(triple);
        if (text != nullptr) module_.target = text;
        lib_.clang_disposeString(triple);
        lib_.clang_TargetInfo_dispose(target);
    }

    const CXCursor root = lib_.clang_getTranslationUnitCursor(tu);
    lib_.clang_visitChildren(
        root,
        [](CXCursor cursor, CXCursor, CXClientData data) {
            static_cast<Binder*>(data)->collectDeclarations(cursor, {});
            return CXChildVisit_Continue;
        },
        this);
    lib_.clang_visitChildren(
        root,
        [](CXCursor cursor, CXCursor, CXClientData data) {
            static_cast<Binder*>(data)->collectDefinitions(cursor, {});
            return CXChildVisit_Continue;
        },
        this);

    module_.classes.clear();
    for (ClassDecl& decl : classes_) {
        if (!decl.rejected) module_.classes.push_back(decl.model);
    }
    module_.enums.clear();
    for (EnumDecl& decl : enums_) module_.enums.push_back(decl.model);

    lib_.clang_disposeTranslationUnit(tu);
    lib_.clang_disposeIndex(index);
    return true;
}

// -----------------------------------------------------------------------------
// Pass 1: declarations
// -----------------------------------------------------------------------------
void Binder::collectDeclarations(CXCursor cursor,
                                 const std::vector<std::string>& ns) {
    const CXCursorKind kind = lib_.clang_getCursorKind(cursor);
    if (kind == CXCursor_Namespace) {
        std::vector<std::string> nested = ns;
        const std::string name = cursorSpelling(cursor);
        if (!name.empty()) nested.push_back(name);
        std::pair<Binder*, const std::vector<std::string>*> context{this,
                                                                    &nested};
        lib_.clang_visitChildren(
            cursor,
            [](CXCursor child, CXCursor, CXClientData data) {
                auto* pair =
                    static_cast<std::pair<Binder*, const std::vector<std::string>*>*>(
                        data);
                pair->first->collectDeclarations(child, *pair->second);
                return CXChildVisit_Continue;
            },
            &context);
        return;
    }
    if (kind == CXCursor_ClassDecl || kind == CXCursor_StructDecl ||
        kind == CXCursor_UnionDecl) {
        collectClass(cursor, ns);
        return;
    }
    if (kind == CXCursor_EnumDecl) {
        collectEnum(cursor, ns);
        return;
    }
    if (kind == CXCursor_ClassTemplate ||
        kind == CXCursor_ClassTemplatePartialSpecialization) {
        rejectCursor(cursor, "class template '" + cursorSpelling(cursor) + "'",
                     "templates are not supported");
    } else if (kind == CXCursor_FunctionTemplate) {
        rejectCursor(cursor, "function template '" + cursorSpelling(cursor) + "'",
                     "templates are not supported");
    } else if (kind == CXCursor_FunctionDecl && inBoundHeader(cursor)) {
        const std::string usr = cursorUSR(cursor);
        if (seenFunctions_.insert(usr).second) {
            ++functionCounts_[qualifiedName(cursor)];
        }
    }
}

void Binder::collectClass(CXCursor cursor, const std::vector<std::string>& ns) {
    if (!inBoundHeader(cursor)) return;
    const std::string name = cursorSpelling(cursor);
    if (name.empty()) {
        rejectCursor(cursor, "record",
                     "anonymous records have no stable C++ name");
        return;
    }
    const std::string cpp = qualifiedName(cursor);
    const auto existing = classIndex_.find(cpp);
    if (existing != classIndex_.end()) {
        if (lib_.clang_isCursorDefinition(cursor)) {
            classes_[existing->second].cursor = cursor;
        }
        return;
    }

    int bases = 0;
    bool virtualBase = false;
    struct BaseState {
        Binder* self;
        int count;
        bool virtualBase;
    } state{this, 0, false};
    lib_.clang_visitChildren(
        cursor,
        [](CXCursor child, CXCursor, CXClientData data) {
            auto* s = static_cast<BaseState*>(data);
            if (s->self->lib_.clang_getCursorKind(child) !=
                CXCursor_CXXBaseSpecifier) {
                return CXChildVisit_Continue;
            }
            ++s->count;
            if (s->self->lib_.clang_isVirtualBase(child)) s->virtualBase = true;
            return CXChildVisit_Continue;
        },
        &state);
    bases = state.count;
    virtualBase = state.virtualBase;
    (void)bases;
    (void)virtualBase;

    ClassDecl decl;
    decl.cursor = cursor;
    decl.model.name = uniqueName(cp3SafeIdent(name), "class");
    decl.model.cppQualified = cpp;
    if (bases > 1) {
        decl.rejected = true;
        rejectCursor(cursor, "class '" + cpp + "'",
                     "multiple inheritance is not supported");
    } else if (virtualBase) {
        decl.rejected = true;
        rejectCursor(cursor, "class '" + cpp + "'",
                     "virtual bases are not supported");
    } else {
        classIndex_[cpp] = classes_.size();
    }
    classes_.push_back(std::move(decl));
    std::vector<std::string> nested = ns;
    nested.push_back(name);
    std::pair<Binder*, const std::vector<std::string>*> context{this, &nested};
    lib_.clang_visitChildren(
        cursor,
        [](CXCursor child, CXCursor, CXClientData data) {
            auto* pair =
                static_cast<std::pair<Binder*, const std::vector<std::string>*>*>(
                    data);
            pair->first->collectDeclarations(child, *pair->second);
            return CXChildVisit_Continue;
        },
        &context);
}

void Binder::collectEnum(CXCursor cursor, const std::vector<std::string>& ns) {
    (void)ns;
    if (!inBoundHeader(cursor)) return;
    const std::string name = cursorSpelling(cursor);
    if (name.empty()) {
        rejectCursor(cursor, "enum",
                     "anonymous enums have no stable C++ name");
        return;
    }
    const std::string cpp = qualifiedName(cursor);
    const auto existing = enumIndex_.find(cpp);
    if (existing != enumIndex_.end()) {
        if (lib_.clang_isCursorDefinition(cursor)) {
            EnumDecl& decl = enums_[existing->second];
            decl.cursor = cursor;
            decl.model.members.clear();
            collectEnumMembers(cursor, decl.model);
        }
        return;
    }

    EnumDecl decl;
    decl.cursor = cursor;
    decl.model.name = uniqueName(cp3SafeIdent(name), "enum");
    decl.model.cppQualified = cpp;
    collectEnumMembers(cursor, decl.model);
    enumIndex_[cpp] = enums_.size();
    enums_.push_back(std::move(decl));
}

void Binder::collectEnumMembers(CXCursor cursor, NativeEnum& model) {
    std::pair<Binder*, NativeEnum*> members{this, &model};
    lib_.clang_visitChildren(
        cursor,
        [](CXCursor child, CXCursor, CXClientData data) {
            auto* pair = static_cast<std::pair<Binder*, NativeEnum*>*>(data);
            if (pair->first->lib_.clang_getCursorKind(child) !=
                CXCursor_EnumConstantDecl) {
                return CXChildVisit_Continue;
            }
            const std::string member = pair->first->cursorSpelling(child);
            pair->second->members.push_back(
                NativeEnumMember{cp3SafeIdent(member), member});
            return CXChildVisit_Continue;
        },
        &members);
}

