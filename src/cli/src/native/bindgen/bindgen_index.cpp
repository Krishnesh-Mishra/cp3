// =============================================================================
// src/cli/src/native/bindgen_index.cpp - the generated `.cp3/native/<id>/index.cp3`.
//
// OWNERSHIP: cli module (native-install). Part of the binder (bindgen.hpp).
//
// The index module is ordinary cp3: exported signatures with no bodies. It is
// the human-readable, editor-visible half of a binding; `native.json` remains
// the source of truth the compiler loads. Declarations bindgen refused are
// listed in the header comment so nothing disappears silently.
// =============================================================================
#include <string>

#include "native/bindgen/bindgen_internal.hpp"

namespace cp3::cli::native {

namespace {

std::string oneLine(const std::string& text) {
    std::string out;
    out.reserve(text.size());
    for (const char c : text) {
        out.push_back(c == '\n' || c == '\r' ? ' ' : c);
    }
    return out;
}

bool typeUsesBuffer(const Type& type) {
    if (type.kind == TypeKind::Class && type.name == "Buffer") return true;
    for (const Type& part : type.parts) {
        if (typeUsesBuffer(part)) return true;
    }
    return false;
}

bool functionUsesBuffer(const NativeFunction& fn) {
    if (typeUsesBuffer(fn.returnType)) return true;
    for (const NativeParam& param : fn.params) {
        if (typeUsesBuffer(param.type)) return true;
    }
    return false;
}

bool moduleUsesBuffer(const NativeModule& module) {
    for (const NativeFunction& fn : module.functions) {
        if (functionUsesBuffer(fn)) return true;
    }
    for (const NativeBoundClass& cls : module.classes) {
        for (const NativeField& field : cls.fields) {
            if (typeUsesBuffer(field.type)) return true;
        }
        for (const NativeFunction& method : cls.methods) {
            if (functionUsesBuffer(method)) return true;
        }
    }
    return false;
}

}  // namespace

std::string renderIndexModule(const NativeModule& module) {
    std::string out;
    out += "// Generated by `cp3 native-install` for native binding '" +
           module.id + "'.\n";
    out += "// Source: " + oneLine(module.source) + "\n";
    out += "// This module declares the beta-one surface; it has no runtime code.\n";
    out += "// The compiler loads `.cp3/native/" + module.id +
           "/native.json` for the\n";
    out += "// C++ names, argument conversions and link metadata.\n";
    if (!module.rejected.empty()) {
        out += "//\n";
        out += "// Rejected declarations (not exposed by this binding):\n";
        for (const std::string& note : module.rejected) {
            out += "//   - " + oneLine(note) + "\n";
        }
    }
    out += "\n";

    // `Buffer` is a named std/buffer type; import it so the index checks cleanly.
    if (moduleUsesBuffer(module)) out += "import { Buffer } from \"std/buffer\";\n\n";

    for (const NativeEnum& en : module.enums) {
        out += "export enum " + en.name + " {\n";
        for (const NativeEnumMember& member : en.members) {
            out += "    " + member.name + ",\n";
        }
        out += "}\n\n";
    }
    for (const NativeBoundClass& cls : module.classes) {
        out += "export class " + cls.name + " {\n";
        for (const NativeField& field : cls.fields) {
            out += "    " + field.name + ": " + cp3TypeText(module, field.type) +
                   ";\n";
        }
        for (const NativeFunction& method : cls.methods) {
            std::string line = method.isStatic ? "    static " : "    ";
            line += "function " + method.name + "(";
            for (std::size_t i = 0; i < method.params.size(); ++i) {
                if (i != 0) line += ", ";
                line += method.params[i].name + ": " +
                        cp3TypeText(module, method.params[i].type);
            }
            line += "): " + cp3TypeText(module, method.returnType) + ";\n";
            out += line;
        }
        out += "}\n\n";
    }
    for (const NativeFunction& fn : module.functions) {
        out += "export function " + fn.name + "(";
        for (std::size_t i = 0; i < fn.params.size(); ++i) {
            if (i != 0) out += ", ";
            out += fn.params[i].name + ": " +
                   cp3TypeText(module, fn.params[i].type);
        }
        out += "): " + cp3TypeText(module, fn.returnType) + ";\n";
    }
    if (!module.functions.empty()) out += "\n";
    return out;
}

}  // namespace cp3::cli::native
